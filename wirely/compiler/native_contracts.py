"""Generate the Python files that describe the native code of Wirely's libraries.

tools/generate-native-types writes them from Wirely declarations, together with
the record classes of the binary program format declared in wirely/program/format.wrl.
contract_sources() also generates the contracts of other native interfaces,
such as those that tests declare.
"""

from __future__ import annotations

import contextlib
import dataclasses
import importlib
import io
import keyword
import os
import re
import textwrap
from collections.abc import Callable, Iterable, Iterator, Mapping, Sequence
from pathlib import Path
from typing import Any, TypeVar

import wirely
from wirely.runtime import signatures

package_root = Path(wirely.__file__).resolve().parent
repository_root = package_root.parent
format_records_path = package_root / 'program/format.wrl'

HEADER = '# Generated by tools/generate-native-types; do not edit.\n'

Interfaces = tuple[dict[str, signatures.Initializer], dict[str, signatures.Procedure], dict[str, signatures.Function]]

T = TypeVar('T')

# Python names that keyword arguments must not use.
_reserved_names = frozenset({'self', 'services'})


def snake_case(key: str) -> str:
    """Return the Python name of a binding key, such as chip_device_file for ChipDeviceFile."""
    words = re.sub(r'(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])', '_', key).lower()
    name = re.sub(r'[^a-z0-9_]', '_', words)
    if not name or name[0].isdigit():
        name = '_' + name
    if keyword.iskeyword(name) or name in _reserved_names:
        name += '_'
    return name


def camel_case(name: str) -> str:
    """Return a class name part, such as SendValue for send_value."""
    result = ''.join(part[:1].upper() + part[1:] for part in re.split(r'[^0-9A-Za-z]+', name))
    return '_' + result if not result or result[0].isdigit() else result


def module_name(namespace: str) -> str:
    """Return the name of a namespace's contract module, such as two_n for TwoN."""
    return '_'.join(snake_case(part) for part in namespace.split('.'))


def contract_location(kind: str, native_name: str) -> tuple[str, str]:
    """Return the contract module and attribute of an 'initializer', 'procedure', or 'function'."""
    if kind in ('initializer', 'procedure'):
        prefix, _, procedure = native_name.rpartition(':')
        namespace, _, node_type = prefix.rpartition('.')
        attribute = camel_case(node_type) + camel_case(procedure)
    else:
        namespace, _, name = native_name.rpartition('.')
        attribute = '_' + camel_case(name)
    if not namespace:
        raise ValueError(f'Native name `{native_name}` has no namespace')
    return module_name(namespace), attribute


def _python_names(where: str, items: Iterable[tuple[str, str]]) -> dict[str, str]:
    """Map each (label, key) to its key's Python name, rejecting collisions."""
    names: dict[str, str] = {}
    labels: dict[str, str] = {}
    for label, key in items:
        name = snake_case(key)
        if name in labels:
            raise ValueError(f'{where}: {labels[name]} and {label} `{key}` have the same Python name `{name}`')
        labels[name] = f'{label} `{key}`'
        names[key] = name
    return names


def struct_field_names(value_type: Any) -> dict[str, str]:
    """Map each field of a struct to its NamedTuple field name, such as length_bytes for LengthBytes."""
    names = _python_names(f'Struct `{value_type.name}`', (('field', field) for field in value_type.fields))
    # Fields must not shadow tuple methods such as count().
    return {field: name + '_' if hasattr(tuple, name) else name for field, name in names.items()}


class _Imports:
    """The names a generated module imports, at runtime or for type checking only."""

    def __init__(self, module: str | None = None, native_locations: Mapping[str, str] = {}) -> None:
        self.native_locations = native_locations
        self._module = module  # Names of this module are not imported.
        self._modules: set[str] = set()
        self._names: dict[tuple[bool, str], set[str]] = {}

    def module(self, name: str) -> None:
        self._modules.add(name)

    def add(self, module: str, name: str, *, type_checking: bool = False) -> str:
        if module != self._module:
            self._names.setdefault((type_checking, module), set()).add(name)
        return name

    def names(self) -> set[str]:
        return {*self._modules, *(name for names in self._names.values() for name in names)}

    def lines(self) -> list[str]:
        def name_key(name: str) -> tuple[int, list[Any]]:
            # Constants, then classes, then functions; numbers in names in numeric order.
            category = 0 if name.isupper() else 1 if name[0].isupper() else 2
            return category, [int(part) if part.isdigit() else part for part in re.split(r'(\d+)', name)]

        def from_lines(type_checking: bool) -> list[str]:
            modules = sorted((module for checking, module in self._names if checking == type_checking),
                             key=lambda module: (module.startswith('wirely'), module))
            lines = []
            for index, module in enumerate(modules):
                if index and module.startswith('wirely') and not modules[index - 1].startswith('wirely'):
                    lines.append('')
                names = sorted(self._names[type_checking, module], key=name_key)
                line = f'from {module} import {", ".join(names)}'
                if len(line) > 110:
                    wrapped = textwrap.wrap(', '.join(names) + ',', 106, break_long_words=False)
                    line = '\n'.join([f'from {module} import (', *('    ' + part for part in wrapped), ')'])
                lines.append(line)
            return lines

        lines = [f'import {module}' for module in sorted(self._modules)]
        lines += from_lines(False)
        checking = from_lines(True)
        if checking:
            lines += ['', 'if TYPE_CHECKING:', *('    ' + line if line else '' for line in checking)]
        return lines


_builtins = {
    'unit': ('wirely.types.unit', 'Unit'), 'boolean': (None, 'bool'), 'string': (None, 'str'),
}


def opaque_location(native_name: str, package: str = 'wirely') -> tuple[str, str]:
    """Return the module and class name implementing an opaque struct, such as wirely.native.std, Duration."""
    namespace, _, name = native_name.rpartition('.')
    if not namespace:
        raise ValueError(f'Native name `{native_name}` has no namespace')
    return f'{package}.native.{module_name(namespace)}', name


def class_name(native_name: str) -> str:
    """Return the class name of a native enum or struct, such as StdFormatParts."""
    return native_name.replace('.', '')


def annotation(signature: signatures.SignatureType | signatures.ResourceType, imports: _Imports,
               resource_classes: Mapping[str, tuple[str, str]], strict: bool = True) -> str:
    """Return the annotation of a value or resource as native code receives it."""
    from wirely.types.integers import integer_class

    if isinstance(signature, signatures.TypeVar):
        return imports.add('wirely.types.value_types', 'DynamicValue')
    if isinstance(signature, signatures.Builtin):
        if signature.name == 'type':
            imports.add('typing', 'Any')
            return imports.add('wirely.types.value_types', 'ValueType') + '[Any]'
        module, name = _builtins[signature.name]
        return name if module is None else imports.add(module, name)
    if isinstance(signature, signatures.Int):
        return imports.add('wirely.types.integers', integer_class(signature.bits, signature.signed).__name__)
    if isinstance(signature, signatures.Option):
        inner = annotation(signature.inner, imports, resource_classes, strict)
        return f'{imports.add("wirely.types.option", "Some")}[{inner}] | None'
    if isinstance(signature, signatures.List):
        return f'tuple[{annotation(signature.inner, imports, resource_classes, strict)}, ...]'
    if isinstance(signature, signatures.Opaque):
        module, name = opaque_location(signature.native_name)
        module = imports.native_locations.get(signature.native_name, module)
        # Implementation modules import their contracts.
        return imports.add(module, name, type_checking=True)
    if isinstance(signature, (signatures.Enum, signatures.Struct)):
        module = imports.native_locations.get(signature.native_name,
                 'wirely.generated.enums' if isinstance(signature, signatures.Enum) else 'wirely.generated.structs')
        name = class_name(signature.native_name)
        if not strict and not hasattr(importlib.import_module(module), name):
            # Enums and structs that only tests declare have no generated class.
            imports.add('typing', 'Any')
            return 'Any'
        return imports.add(module, name)
    if isinstance(signature, signatures.ResourceType):
        location = resource_classes.get(signature.native_name)
        if location is not None:
            return imports.add(*location, type_checking=True)
        if strict:
            raise ValueError(f'Cannot find the Python class of resource type `{signature.native_name}`')
        return 'object'
    raise ValueError(f'Unknown signature type {signature!r}')


def resource_classes(interfaces: Interfaces | None = None) -> dict[str, tuple[str, str]]:
    """Return conventional resource exports without importing implementation modules."""
    if interfaces is None:
        from wirely.generated import extension
        interfaces = ({name: entry.signature for name, entry in extension.states.items()},
                      {name: entry.signature for name, entry in extension.procedures.items()},
                      {name: entry.signature for name, entry in extension.functions.items()})
    names = set()
    for table in interfaces[:2]:
        for signature in table.values():
            for port in (*signature.depends.values(), *signature.produces.values()):
                if isinstance(port.type, signatures.ResourceType):
                    names.add(port.type.native_name)
    return {name: ('wirely.native.' + module_name(name.rpartition('.')[0]), name.rpartition('.')[2])
            for name in sorted(names)}


def _parameters(parameters: Iterable[tuple[str, str]]) -> list[str]:
    """Return the lines of a keyword-only method signature after its name."""
    return ['(', '        self, *,', *(f'        {name}: {text},' for name, text in parameters)]


def _call(target: str, arguments: Iterable[tuple[str, str]]) -> list[str]:
    return [f'        result = {target}(', *(f'            {name}={value},' for name, value in arguments), '        )']


def _outputs(lines: Iterable[tuple[str, str]]) -> list[str]:
    lines = list(lines)
    if not lines:
        return ['        return {}']
    return ['        return {', *(f'            {key!r}: {value},' for key, value in lines), '        }']


def _result_class(name: str, description: str, fields: Iterable[tuple[str, str]]) -> list[str]:
    lines = ['@dataclass(frozen=True, slots=True, kw_only=True)', f'class {name}:', f'    """{description}"""']
    fields = list(fields)
    if fields:
        lines += ['', *(f'    {field}: {text}' for field, text in fields)]
    return lines + ['', '']


def _port_type(port: signatures.Port) -> signatures.SignatureType | signatures.ResourceType:
    if port.kind == 'event':
        assert not isinstance(port.type, signatures.ResourceType)
        return signatures.Option(port.type)
    return port.type


def _initializer_code(native_name: str, signature: signatures.Initializer, imports: _Imports,
                      resource_classes: Mapping[str, tuple[str, str]], strict: bool) -> list[str]:
    _, contract = contract_location('initializer', native_name)
    result = contract + 'Result'
    where = f'Native initializer {native_name}'

    def annotate(item: signatures.SignatureType | signatures.ResourceType) -> str:
        return 'object' if isinstance(item, signatures.TypeVar) else annotation(item, imports, resource_classes, strict)

    for key, port in [*signature.depends.items(), *signature.produces.items()]:
        if port.kind not in ('resource', 'fixed') or port.multi:
            raise ValueError(f'{where}: `{key}` must be a single fixed value')
    arguments = _python_names(where, [*(('input', key) for key in signature.depends),
                                      *(('compile-time read', key) for key in signature.uses)])
    outputs = _python_names(where, (('output', key) for key in signature.produces))
    if outputs:
        literal = imports.add('typing', 'Literal') + f'[{", ".join(repr(name) for name in outputs.values())}]'
    else:
        literal = imports.add('typing', 'Never')
    types = {key: annotate(port.type) for key, port in signature.depends.items()}
    # Compile-time reads are never resources.
    types.update((key, annotation(item, imports, resource_classes, strict)) for key, item in signature.uses.items())
    for name in ('NativeState', 'StateServices', 'InitializerAdapter', 'InterfaceBinding'):
        imports.add('wirely.runtime.native_api', name)
    imports.add('wirely.types', 'InternalValue')
    imports.add('typing', 'Any')
    imports.add('typing', 'cast')
    imports.module('abc')
    imports.add('dataclasses', 'dataclass')

    def value(key: str) -> str:
        source = f"binding.fixed({key!r})" if key in signature.depends else f'binding.use({key!r})'
        return f'cast({types[key]!r}, {source})'

    parameters = _parameters([('services', f'StateServices[{literal}]'),
                              *((name, types[key]) for key, name in arguments.items())])
    lines = _result_class(result, f'Fixed outputs of native initializer {native_name}.',
                          ((outputs[key], annotate(port.type)) for key, port in signature.produces.items()))
    lines += [
        f'class {contract}(NativeState[{literal}], abc.ABC):',
        f'    """Native initializer {native_name}; initialize() returns its fixed outputs."""',
        '',
        '    @abc.abstractmethod',
        '    def initialize' + parameters[0],
        *parameters[1:],
        f'    ) -> {result}:',
        '        ...',
        '',
        '',
        f'class _{contract}Adapter(InitializerAdapter):',
        f'    output_keys = {{{", ".join(f"{name!r}: {key!r}" for key, name in outputs.items())}}}',
        '',
        '    def initialize(self, state: NativeState[Any], services: StateServices[Any],',
        '                   binding: InterfaceBinding) -> dict[str, InternalValue]:',
        f'        assert isinstance(state, {contract})',
        *_call('state.initialize', [('services', 'services'), *((name, value(key)) for key, name in arguments.items())]),
        f'        binding.check_result(result, {result})',
        *_outputs((key, f'binding.output({key!r}, result.{name})') for key, name in outputs.items()),
        '',
        '',
        f'{contract}._adapter = _{contract}Adapter()',
    ]
    return lines


def _load_code(native_name: str, signature: signatures.Procedure, imports: _Imports,
               resource_classes: Mapping[str, tuple[str, str]], strict: bool) -> list[str]:
    """Generate a pure load procedure with a single call and no runtime services."""
    _, contract = contract_location('procedure', native_name)
    result = contract + 'Result'
    where = f'Native load procedure {native_name}'
    for key, port in [*signature.depends.items(), *signature.produces.items()]:
        if port.kind not in ('fixed', 'resource') or port.multi:
            raise ValueError(f'{where}: `{key}` must be a single fixed value')
    arguments = _python_names(where, [*(('input', key) for key in signature.depends),
                                      *(('compile-time read', key) for key in signature.uses)])
    outputs = _python_names(where, (('output', key) for key in signature.produces))

    def annotate(item: signatures.SignatureType | signatures.ResourceType) -> str:
        return 'object' if isinstance(item, signatures.TypeVar) else annotation(item, imports, resource_classes, strict)

    types = {key: annotate(port.type) for key, port in signature.depends.items()}
    types.update((key, annotation(item, imports, resource_classes, strict)) for key, item in signature.uses.items())
    for name in ('NativeProcedure', 'PreparationServices', 'ProcedureServices', 'ProcedureAdapter', 'InterfaceBinding'):
        imports.add('wirely.runtime.native_api', name)
    imports.add('wirely.types', 'InternalValue')
    imports.add('collections.abc', 'Mapping')
    imports.add('typing', 'cast')
    imports.module('abc')
    imports.add('dataclasses', 'dataclass')
    parameters = _parameters([('services', 'PreparationServices'),
                              *((name, types[key]) for key, name in arguments.items())])
    lines = _result_class(result, f'Fixed outputs of native load procedure {native_name}.',
                          ((outputs[key], annotate(port.type)) for key, port in signature.produces.items()))
    lines += [
        f'class {contract}(NativeProcedure, abc.ABC):',
        f'    """Native load procedure {native_name}."""',
        '', '    @abc.abstractmethod',
        '    def load' + parameters[0], *parameters[1:], f'    ) -> {result}:', '        ...', '', '',
        f'class _{contract}Adapter(ProcedureAdapter):',
        '    def prepare(self, procedure: NativeProcedure, services: PreparationServices, binding: InterfaceBinding) -> None:',
        '        raise ValueError("Load procedures cannot be prepared for runtime execution")', '',
        '    def run(self, procedure: NativeProcedure, services: ProcedureServices, binding: InterfaceBinding,',
        '            inputs: Mapping[str, InternalValue]) -> dict[str, InternalValue]:',
        '        raise ValueError("Load procedures cannot run during a step")', '',
        '    def load(self, procedure: NativeProcedure, services: PreparationServices, binding: InterfaceBinding,',
        '             inputs: Mapping[str, InternalValue]) -> dict[str, InternalValue]:',
        f'        assert isinstance(procedure, {contract})',
        *_call('procedure.load', [('services', 'services'), *((name,
            f"cast({types[key]!r}, binding.input(inputs, {key!r}))" if key in signature.depends
            else f"cast({types[key]!r}, binding.use({key!r}))") for key, name in arguments.items())]),
        f'        binding.check_result(result, {result})',
        *_outputs((key, f'binding.output({key!r}, result.{name})') for key, name in outputs.items()),
        '', '', f'{contract}._adapter = _{contract}Adapter()',
    ]
    return lines


def _procedure_code(native_name: str, signature: signatures.Procedure, imports: _Imports,
                    resource_classes: Mapping[str, tuple[str, str]], strict: bool) -> list[str]:
    _, contract = contract_location('procedure', native_name)
    result = contract + 'Result'
    where = f'Native procedure {native_name}'

    def annotate(item: signatures.SignatureType | signatures.ResourceType) -> str:
        return annotation(item, imports, resource_classes, strict)

    for key, port in [*signature.depends.items(), *signature.produces.items()]:
        if port.multi:
            raise ValueError(f'{where}: multi port `{key}` is not supported')
    if signature.stage == 'load':
        return _load_code(native_name, signature, imports, resource_classes, strict)
    resources = [key for key, port in signature.depends.items() if port.kind in ('resource', 'fixed')]
    prepared = _python_names(where, [*(('input', key) for key in resources),
                                     *(('compile-time read', key) for key in signature.uses)])
    inputs = _python_names(where, [*(('input', key) for key in signature.depends),
                                   *(('compile-time read', key) for key in signature.uses)])
    outputs = _python_names(where, (('output', key) for key in signature.produces))
    port_types = {key: ('object' if port.kind == 'fixed' and isinstance(port.type, signatures.TypeVar)
                        else annotate(_port_type(port))) for key, port in signature.depends.items()}
    use_types = {key: annotate(item) for key, item in signature.uses.items()}
    for name in ('NativeProcedure', 'PreparationServices', 'ProcedureServices', 'ProcedureAdapter',
                 'InterfaceBinding'):
        imports.add('wirely.runtime.native_api', name)
    imports.add('wirely.types', 'InternalValue')
    imports.add('collections.abc', 'Mapping')
    imports.add('typing', 'cast')
    imports.module('abc')
    imports.add('dataclasses', 'dataclass')

    def prepared_value(key: str) -> str:
        if key in signature.uses:
            return f'cast({use_types[key]!r}, binding.use({key!r}))'
        return f'cast({port_types[key]!r}, binding.fixed({key!r}))'

    def input_value(key: str) -> str:
        if key in signature.uses:
            return f'cast({use_types[key]!r}, binding.use({key!r}))'
        if signature.depends[key].kind == 'resource':
            return f'cast({port_types[key]!r}, binding.fixed({key!r}))'
        return f'cast({port_types[key]!r}, binding.input(inputs, {key!r}))'

    prepare_parameters = _parameters([('services', 'PreparationServices'),
                                      *((name, use_types[key] if key in signature.uses else port_types[key])
                                        for key, name in prepared.items())])
    run_parameters = _parameters([('services', 'ProcedureServices'),
                                  *((name, use_types[key] if key in signature.uses else port_types[key])
                                    for key, name in inputs.items())])
    lines = _result_class(result, f'Outputs of native procedure {native_name}.',
                          ((outputs[key], annotate(_port_type(port))) for key, port in signature.produces.items()))
    lines += [
        f'class {contract}(NativeProcedure, abc.ABC):',
        f'    """Native procedure {native_name}."""',
        '',
        *(['    @abc.abstractmethod'] if signature.uses else []),
        '    def prepare' + prepare_parameters[0],
        *prepare_parameters[1:],
        '    ) -> None:',
        '        ...' if signature.uses else '        pass',
        '',
        '    @abc.abstractmethod',
        '    def run' + run_parameters[0],
        *run_parameters[1:],
        f'    ) -> {result}:',
        '        ...',
        '',
        '',
        f'class _{contract}Adapter(ProcedureAdapter):',
        '    def prepare(self, procedure: NativeProcedure, services: PreparationServices,',
        '                binding: InterfaceBinding) -> None:',
        f'        assert isinstance(procedure, {contract})',
        *(line.replace('result = ', '', 1) for line in _call(
            'procedure.prepare', [('services', 'services'), *((name, prepared_value(key)) for key, name in prepared.items())])),
        '',
        '    def run(self, procedure: NativeProcedure, services: ProcedureServices, binding: InterfaceBinding,',
        '            inputs: Mapping[str, InternalValue]) -> dict[str, InternalValue]:',
        f'        assert isinstance(procedure, {contract})',
        *_call('procedure.run', [('services', 'services'), *((name, input_value(key)) for key, name in inputs.items())]),
        f'        binding.check_result(result, {result})',
        *_outputs((key, f'binding.output({key!r}, result.{name})') for key, name in outputs.items()),
        '',
        '',
        f'{contract}._adapter = _{contract}Adapter()',
    ]
    return lines


def _function_code(native_name: str, signature: signatures.Function, imports: _Imports,
                   resource_classes: Mapping[str, tuple[str, str]]) -> list[str]:
    _, contract = contract_location('function', native_name)
    parameters = [annotation(parameter, imports, resource_classes) for parameter in signature.parameters]
    implementation = (f'{imports.add("collections.abc", "Callable")}[[{", ".join(parameters)}], '
                      f'{annotation(signature.result, imports, resource_classes)}]')
    for name in ('FunctionBinding', 'FunctionContract'):
        imports.add('wirely.runtime.native_api', name)
    imports.add('wirely.types', 'InternalValue')
    imports.add('collections.abc', 'Sequence')
    adapter = f'_call_{snake_case(contract).rstrip("_")}'
    if parameters:
        imports.add('typing', 'cast')
        call = ['    return binding.result(implementation(',
                *(f'        cast({text!r}, binding.argument(arguments, {index})),'
                  for index, text in enumerate(parameters)),
                '    ))']
    else:
        call = ['    return binding.result(implementation())']
    return [
        f'def {adapter}(',
        f'    implementation: {implementation},',
        '    binding: FunctionBinding,',
        '    arguments: Sequence[InternalValue],',
        ') -> InternalValue:',
        *call,
        '',
        '',
        f'# Native function {native_name}.',
        f'{contract}: FunctionContract[{implementation}] = FunctionContract(',
        f'    {native_name!r}, {adapter})',
    ]


def _constant_function_code(native_name: str, signature: signatures.Function, imports: _Imports,
                            strict: bool) -> list[str]:
    _, contract = contract_location('function', native_name)
    parameters = [annotation(parameter, imports, {}, strict) for parameter in signature.parameters]
    result = annotation(signature.result, imports, {}, strict)
    implementation = contract + 'Implementation'
    imports.add('typing', 'Protocol')
    for name in ('ConstantFunctionContract', 'FunctionServices'):
        imports.add('wirely.compiler.native_functions', name)
    imports.add('collections.abc', 'Sequence')
    if parameters:
        imports.add('typing', 'cast')
    adapter = f'_call_{snake_case(contract).rstrip("_")}'
    arguments = [f'        argument_{index}: {text},' for index, text in enumerate(parameters)]
    return [
        f'class {implementation}(Protocol):',
        f'    """Implementations of constant function {native_name}, receiving its arguments in order."""',
        '',
        '    def __call__(',
        '        self,',
        *arguments,
        *(['        /, *,'] if parameters else ['        *,']),
        '        services: FunctionServices,',
        f'    ) -> {result}:',
        '        ...',
        '',
        '',
        f'def {adapter}(',
        f'    implementation: {implementation},',
        '    arguments: Sequence[object],',
        '    services: FunctionServices,',
        ') -> object:',
        '    return implementation(',
        *(f'        cast({text!r}, arguments[{index}]),' for index, text in enumerate(parameters)),
        '        services=services,',
        '    )',
        '',
        '',
        f'# Constant function {native_name}.',
        f'{contract}: ConstantFunctionContract[{implementation}] = ConstantFunctionContract(',
        f'    {native_name!r}, {adapter})',
    ]


def _module_names(lines: Iterable[str]) -> Iterator[str]:
    """Yield the names that generated code defines at module level."""
    for line in lines:
        match = re.match(r'(?:class |def )?([A-Za-z_][A-Za-z0-9_]*)(?:\(|:| =)', line)
        if match is not None and not line.startswith(' '):
            yield match.group(1)


def contract_sources(interfaces: Interfaces, *, resource_classes: Mapping[str, tuple[str, str]],
                     strict: bool = True, header: str = HEADER,
                     native_locations: Mapping[str, str] = {}) -> dict[str, str]:
    """Return the source of each contract module of runtime native code by module name.

    Unless strict, resource types without a known class are annotated as object,
    and enums and structs without a generated class as Any.
    """
    state_types, procedures, functions = interfaces

    def generate(kind: str, native_name: str, signature: Any, imports: _Imports) -> list[str]:
        if kind == 'initializer':
            return _initializer_code(native_name, signature, imports, resource_classes, strict)
        if kind == 'procedure':
            return _procedure_code(native_name, signature, imports, resource_classes, strict)
        return _function_code(native_name, signature, imports, resource_classes)

    tables = (('initializer', state_types), ('procedure', procedures), ('function', functions))
    return _module_sources(tables, generate, 'the native code', header, native_locations)


def constant_contract_sources(functions: Mapping[str, signatures.Function], *, strict: bool = True,
                              header: str = HEADER, native_locations: Mapping[str, str] = {}) -> dict[str, str]:
    """Return the source of each contract module of constant native functions by module name."""
    def generate(kind: str, native_name: str, signature: Any, imports: _Imports) -> list[str]:
        return _constant_function_code(native_name, signature, imports, strict)

    return _module_sources((('function', functions),), generate, 'the constant functions', header, native_locations)


def _module_sources(tables: Iterable[tuple[str, Mapping[str, Any]]],
                    generate: Callable[[str, str, Any, _Imports], list[str]],
                    description: str, header: str, native_locations: Mapping[str, str]) -> dict[str, str]:
    """Group entries into one module per namespace and return the source of each module by name."""
    entries: dict[str, list[tuple[str, str, Any]]] = {}
    for kind, table in tables:
        for native_name, signature in sorted(table.items()):
            module, _ = contract_location(kind, native_name)
            entries.setdefault(module, []).append((kind, native_name, signature))
    sources = {}
    for module, items in sorted(entries.items()):
        imports = _Imports(native_locations=native_locations)
        body: list[str] = []
        definitions: dict[str, str] = {}
        for kind, native_name, signature in items:
            code = generate(kind, native_name, signature, imports)
            for name in _module_names(code):
                previous = definitions.setdefault(name, native_name)
                if previous != native_name:
                    raise ValueError(f'Contracts of `{previous}` and `{native_name}` both define `{name}`')
            body += ['', '', *code]
        imports.add('__future__', 'annotations')
        for name in sorted(imports.names() & definitions.keys()):
            raise ValueError(f'Contract name `{name}` of `{definitions[name]}` is also an imported name')
        if any(line.startswith('if TYPE_CHECKING:') for line in imports.lines()):
            imports.add('typing', 'TYPE_CHECKING')
        import_lines = imports.lines()
        future = 'from __future__ import annotations'
        import_lines = [line for line in import_lines if line != future]
        while import_lines and not import_lines[0]:
            import_lines.pop(0)
        lines = [header + f'"""Contracts of {description} in namespace {_namespace(items[0])}."""', '',
                 future, '', *import_lines, '',
                 '__all__ = [', *(f'    {name!r},' for name in definitions if not name.startswith('_')),
                 ']', *body, '']
        sources[module] = '\n'.join(lines)
    return sources


def _namespace(item: tuple[str, str, Any]) -> str:
    kind, native_name, _ = item
    return native_name.rpartition(':')[0].rpartition('.')[0] if kind == 'procedure' else native_name.rpartition('.')[0]



def compile_library() -> Any:
    from wirely.compiler import standard_library_sources

    graph = compile_declarations(standard_library_sources())
    if graph is None:
        raise ValueError('Compiling the standard library failed')
    return graph


def compile_declarations(sources: Sequence[Any]) -> Any:
    """Compile parsed sources without loading native implementations.

    Generation needs declarations, not values, so literals of opaque structs, which need their
    implementations, parse to placeholder values.
    """
    import wirely.compiler
    from wirely.compiler.attributes import ParsedFile
    from wirely.runtime.extensions import RuntimeNativeExtension

    def compile(sources: Sequence[Any], extensions: Sequence[Any] = ()) -> Any:
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            # Generated files follow declaration order, also in shuffle test runs.
            graph = wirely.compiler.compile_strs(sources, shuffle_seed=None, include_builtin_extensions=False,
                                                 extensions=extensions)
        if graph is None:
            raise ValueError(f'Compiling native declarations failed:\n{output.getvalue()}')
        return graph

    # Type declarations have no literals of opaque structs and give their native names and field types.
    types = compile([dataclasses.replace(source, tree=ParsedFile(_type_declarations(source.tree),
                                                                inner_attributes=source.tree.inner_attributes))
                     for source in sources])
    opaque_types = {value_type.native_name: _placeholder_opaque(value_type)
                    for value_type, _ in native_opaque_types(types)}
    return compile(sources, [RuntimeNativeExtension(opaque_types=opaque_types)])


def _type_declarations(declarations: Iterable[Any]) -> list[Any]:
    """Return the struct and enum declarations with their namespaces."""
    from wirely.compiler import model

    result: list[Any] = []
    for declaration in declarations:
        if isinstance(declaration, model.DeclarationLibrary):
            result.append(dataclasses.replace(declaration, declarations=tuple(_type_declarations(declaration.declarations))))
        elif isinstance(declaration, (model.DeclarationStructType, model.DeclarationEnumType)):
            result.append(declaration)
    return result


def _placeholder_opaque(value_type: Any) -> Any:
    """Return an implementation of an opaque struct whose literals parse to its default value."""
    from wirely.compiler.native_signatures import signature_type
    from wirely.runtime.extensions import NativeTypes
    from wirely.runtime.native_values import to_native
    from wirely.types.value_types import NativeOpaque

    fields = tuple(to_native(None, field_type, field_type.default_value(), native_types=NativeTypes())
                   for field_type in value_type.fields.values())

    class Placeholder:
        @staticmethod
        def parse(text: str) -> Placeholder:
            return Placeholder()

        def to_fields(self) -> tuple:
            return fields

    signatures = tuple(signature_type(field_type, {}, f'Opaque struct {value_type.name}')
                       for field_type in value_type.fields.values())
    return NativeOpaque(signatures, lambda: Placeholder)


def function_signatures(graph: Any, *, constant: bool) -> dict[str, signatures.Function]:
    from wirely.compiler.native_signatures import function_signatures as signatures_of
    return signatures_of(graph, constant=constant)


def library_interfaces(*graphs: Any) -> Interfaces:
    """Return the native interfaces of compiled libraries, rejecting duplicate native names."""
    from wirely.compiler.native_signatures import native_signatures

    def merge(table: dict[str, T], entries: Mapping[str, T]) -> None:
        for name in sorted(entries.keys() & table.keys()):
            raise ValueError(f'Duplicate native interface `{name}`')
        table.update(entries)

    result: Interfaces = ({}, {}, {})
    for graph in graphs:
        state_types, procedures, functions = native_signatures(graph)
        merge(result[0], state_types)
        merge(result[1], procedures)
        merge(result[2], functions)
    return result


def native_enums(scope: Any) -> Iterator[tuple[Any, Any]]:
    """Yield (TypeEnum, declaration) for each native enum declared in a scope and its namespaces."""
    for definition in scope.enum_types.values():
        if definition.value_type.native_name is not None:
            yield definition.value_type, definition.declaration
    for library in scope.libraries.values():
        yield from native_enums(library)


def native_structs(scope: Any) -> Iterator[tuple[Any, Any]]:
    """Yield (TypeStruct, declaration) for each native struct declared in a scope and its namespaces."""
    for definition in scope.struct_types.values():
        if definition.declaration.is_opaque:
            continue
        value_type = definition.resolve_fields()
        if value_type.native_name is not None:
            yield value_type, definition.declaration
    for library in scope.libraries.values():
        yield from native_structs(library)


def native_opaque_types(scope: Any) -> Iterator[tuple[Any, Any]]:
    """Yield (TypeStruct, declaration) for each opaque struct declared in a scope and its namespaces."""
    for definition in scope.struct_types.values():
        if definition.declaration.is_opaque:
            yield definition.resolve_fields(), definition.declaration
    for library in scope.libraries.values():
        yield from native_opaque_types(library)


def native_resources(scope: Any) -> Iterator[tuple[str, Any]]:
    """Yield native resource names and declarations, including resources without consumers."""
    for definition in scope.resource_types.values():
        yield definition.value_type.native_name, definition.declaration
    for nested in (*scope.libraries.values(), *scope.node_types.values()):
        yield from native_resources(nested)


def signature_names(value: Any) -> Iterator[str]:
    """Yield the class names a signature description's code uses."""
    yield type(value).__name__
    for name in value.__dataclass_fields__:
        field = getattr(value, name)
        if isinstance(field, (signatures.SignatureType, signatures.ResourceType)):
            yield from signature_names(field)


def source_comment(name: str, declaration: Any, source_root: Path = repository_root) -> str:
    filename = Path(declaration.source_position.filename).resolve()
    return f'# {name} in {os.path.relpath(filename, source_root)}'


def generate_enums(graph: Any, source_paths: set[str] | None = None, *,
                   source_root: Path = repository_root) -> str:
    classes = sorted((class_name(value_type.native_name), value_type.native_name, value_type, declaration)
                     for value_type, declaration in native_enums(graph)
                     if source_paths is None or declaration.source_position.filename in source_paths)
    lines = [HEADER + '"""Python enums for native enum types."""', '']
    if not all(value_type.is_open for _, _, value_type, _ in classes):
        lines += ['import enum', '']
    lines += ['from wirely.types.value_types import NativeEnum, OpenIntEnum', '',
              '__all__ = [', *(f'    {name!r},' for name, *_ in classes), ']', '']
    for python_name, name, value_type, declaration in classes:
        if not value_type.members:
            # Python cannot look up values of an enum without members.
            raise ValueError(f'Native enum `{value_type.name}` must have members')
        underlying = value_type.underlying_type
        base = (f'OpenIntEnum, minimum={underlying.min_value}, maximum={underlying.max_value}'
                if value_type.is_open else 'enum.IntEnum')
        lines += ['', source_comment(value_type.name, declaration, source_root), f'class {python_name}({base}):']
        lines += [f'    {member} = {number}' for member, number in value_type.members.items()]
        lines.append('')
    lines += ['', '# Expected native enums by native name.', '_native_enum_types: dict[str, NativeEnum] = {']
    lines += [f'    {name!r}: NativeEnum({python_name}, is_open={value_type.is_open}, '
              f'underlying_type={str(value_type.underlying_type)!r}),'
              for python_name, name, value_type, _ in classes]
    lines += ['}', '']
    return '\n'.join(lines)


def generate_structs(graph: Any, source_paths: set[str] | None = None, *,
                     package: str = "wirely", native_locations: Mapping[str, str] = {},
                     source_root: Path = repository_root) -> str:
    from wirely.compiler.native_signatures import signature_type

    classes = sorted((class_name(value_type.native_name), value_type.native_name, value_type, declaration)
                     for value_type, declaration in native_structs(graph)
                     if source_paths is None or declaration.source_position.filename in source_paths)
    fields = {name: [signature_type(field_type, {}, f'Native struct {value_type.name}')
                     for field_type in value_type.fields.values()]
              for _, name, value_type, _ in classes}
    opaque = sorted((value_type.native_name, value_type, declaration)
                    for value_type, declaration in native_opaque_types(graph)
                    if source_paths is None or declaration.source_position.filename in source_paths)
    opaque_fields = {name: [signature_type(field_type, {}, f'Opaque struct {value_type.name}')
                            for field_type in value_type.fields.values()]
                     for name, value_type, _ in opaque}
    imports = _Imports(package + '.generated.structs', native_locations)
    imports.add('typing', 'NamedTuple')
    imports.add('wirely.types.value_types', 'NativeOpaque')
    imports.add('wirely.types.value_types', 'NativeStruct')
    for name in sorted({name for types in (*fields.values(), *opaque_fields.values())
                        for field in types for name in signature_names(field)}):
        imports.add('wirely.runtime.signatures', name)
    bodies = []
    for python_name, name, value_type, declaration in classes:
        body = ['', source_comment(value_type.name, declaration, source_root), f'class {python_name}(NamedTuple):']
        names = struct_field_names(value_type)
        body += [f'    {names[field]}: {annotation(field_type, imports, {})}'
                 for field, field_type in zip(value_type.fields, fields[name])]
        if not value_type.fields:
            body.append('    pass')
        bodies += body + ['']
    lines = [HEADER + '"""Python classes for native struct types."""', '',
             'from __future__ import annotations', '', *imports.lines(), '',
             '__all__ = [', *(f'    {name!r},' for name, *_ in classes), ']', '', *bodies]
    lines += ['', '# Expected native structs by native name.', '_native_struct_types: dict[str, NativeStruct] = {']
    for python_name, name, *_ in classes:
        lines.append(f'    {name!r}: NativeStruct({python_name}, {_field_code(fields[name])}),')
    lines += ['}', '']
    lines += _opaque_lines(opaque, opaque_fields, native_locations)
    return '\n'.join(lines)


def generate_format_records(graph: Any, *, source_root: Path = repository_root) -> str:
    """Return a module with the Python class and the Wirely type of each enum and struct of the binary program format."""
    from wirely.types import TypeBoolean, TypeEnum, TypeInt, TypeStruct

    def position(declaration: Any) -> int:
        return declaration.source_position.meta.start_pos

    enum_definitions = sorted(graph.enum_types.values(), key=lambda definition: position(definition.declaration))
    enums = [definition.value_type for definition in enum_definitions]
    definitions = sorted(graph.struct_types.values(), key=lambda definition: position(definition.declaration))
    value_types = [definition.resolve_fields() for definition in definitions]
    constants: set[str] = set()

    def integer_code(value_type: Any) -> str:
        name = f'{"" if value_type.is_signed else "u"}int{value_type.bits}'
        constants.add(name)
        return name

    def field_code(record: Any, field: str, field_type: Any) -> tuple[str, str]:
        """Return the Python annotation and the Wirely type expression of a field."""
        if isinstance(field_type, TypeInt):
            return 'int', integer_code(field_type)
        if isinstance(field_type, TypeBoolean):
            constants.add('boolean')
            return 'bool', 'boolean'
        if isinstance(field_type, TypeEnum):
            return field_type.name, f'_enums[{field_type.name!r}]'
        if isinstance(field_type, TypeStruct):
            return str(field_type), f'_types[{str(field_type)!r}]'
        raise ValueError(f'Field `{field}` of format record `{record.name}` has unsupported type `{field_type}`')

    classes: list[tuple[int, str, list[str]]] = []
    for enum_definition, value_type in zip(enum_definitions, enums):
        if not value_type.members:
            # Python cannot look up values of an enum without members.
            raise ValueError(f'Format enum `{value_type.name}` must have members')
        underlying = value_type.underlying_type
        base = (f'OpenIntEnum, minimum={underlying.min_value}, maximum={underlying.max_value}'
                if value_type.is_open else 'enum.IntEnum')
        body = ['', source_comment(value_type.name, enum_definition.declaration, source_root),
                f'class {value_type.name}({base}):']
        body += [f'    {member} = {number}' for member, number in value_type.members.items()]
        classes.append((position(enum_definition.declaration), value_type.name, body + ['']))
    for definition, value_type in zip(definitions, value_types):
        names = struct_field_names(value_type)
        body = ['', source_comment(value_type.name, definition.declaration, source_root),
                f'class {value_type.name}(NamedTuple):']
        body += [f'    {names[field]}: {field_code(value_type, field, field_type)[0]}'
                 for field, field_type in value_type.fields.items()]
        if not value_type.fields:
            body.append('    pass')
        classes.append((position(definition.declaration), value_type.name, body + ['']))
    classes.sort(key=lambda item: item[0])

    types = ['', '# Wirely types of the enums.', '_enums: dict[str, TypeEnum] = {}']
    for value_type in enums:
        types.append(f'_enums[{value_type.name!r}] = TypeEnum({value_type.name!r}, {{')
        types += [f'    {member!r}: {number},' for member, number in value_type.members.items()]
        types.append(f'}}, is_open={value_type.is_open}, underlying_type={integer_code(value_type.underlying_type)})')

    # Wirely allows forward references, so the types are ordered with their field types first.
    ordered: list[Any] = []

    def visit(value_type: Any) -> None:
        if value_type.name in {item.name for item in ordered}:
            return
        for field_type in value_type.fields.values():
            if isinstance(field_type, TypeStruct):
                visit(field_type)
        ordered.append(value_type)

    for value_type in value_types:
        visit(value_type)
    types += ['', '# Wirely types of the records, with field types first.', '_types: dict[str, TypeStruct] = {}']
    for value_type in ordered:
        types.append(f'_types[{value_type.name!r}] = TypeStruct({value_type.name!r}, {{')
        types += [f'    {field!r}: {field_code(value_type, field, field_type)[1]},'
                  for field, field_type in value_type.fields.items()]
        types.append('})')
    types += ['', '# Wirely type of each enum class.', 'enum_types: dict[type[enum.IntEnum], TypeEnum] = {',
              *(f'    {value_type.name}: _enums[{value_type.name!r}],' for value_type in enums), '}']
    types += ['', '# Wirely type of each record class.', 'record_types: dict[type[tuple[Any, ...]], TypeStruct] = {',
              *(f'    {value_type.name}: _types[{value_type.name!r}],' for value_type in value_types), '}', '']

    imports = ', '.join(['TypeEnum', 'TypeStruct',
                         *sorted(constants, key=lambda name: (name != 'boolean', len(name), name))])
    lines = [HEADER + '"""Python classes and Wirely types of the enums and records of the binary program format."""',
             '', 'from __future__ import annotations', '', 'import enum', 'from typing import Any, NamedTuple', '',
             f'from wirely.types import {imports}',
             *(['from wirely.types.value_types import OpenIntEnum'] if any(value_type.is_open for value_type in enums)
               else []),
             '', '__all__ = [', *(f'    {name!r},' for _, name, _ in classes), "    'enum_types',", "    'record_types',",
             ']', '', *(line for _, _, body in classes for line in body), *types]
    return '\n'.join(lines)


def _field_code(fields: Sequence[signatures.SignatureType]) -> str:
    return '(' + ', '.join(signature_code(field) for field in fields) + (',' if len(fields) == 1 else '') + ')'


def _opaque_lines(opaque: Sequence[tuple[str, Any, Any]], fields: Mapping[str, list[signatures.SignatureType]],
                  native_locations: Mapping[str, str]) -> list[str]:
    """Return the loaders and the table of the opaque structs."""
    lines = []
    for name, _, _ in opaque:
        module, python_name = opaque_location(name)
        module = native_locations.get(name, module)
        lines += ['', f'def _load_opaque_{module_name(name)}() -> type:', f'    from {module} import {python_name}',
                  f'    return {python_name}', '']
    lines += ['', '# Expected opaque structs by native name.', '_native_opaque_types: dict[str, NativeOpaque] = {']
    lines += [f'    {name!r}: NativeOpaque({_field_code(fields[name])}, _load_opaque_{module_name(name)}),'
              for name, _, _ in opaque]
    lines += ['}', '']
    return lines


def signature_code(value: Any) -> str:
    """Return Python code constructing a signature description."""
    if isinstance(value, signatures.Port):
        port_arguments = [repr(value.kind), signature_code(value.type)] + (['multi=True'] if value.multi else [])
        return f'Port({", ".join(port_arguments)})'
    if isinstance(value, signatures.Function):
        parameters = ', '.join(signature_code(parameter) for parameter in value.parameters)
        return (f'Function(({parameters}{"," if len(value.parameters) == 1 else ""}), '
                f'{signature_code(value.result)})')
    fields = [getattr(value, name) for name in value.__dataclass_fields__]
    arguments = ', '.join(signature_code(field) if isinstance(field, (signatures.SignatureType, signatures.ResourceType))
                          else repr(field) for field in fields)
    return f'{type(value).__name__}({arguments})'


def interface_lines(name: str, value: signatures.Initializer | signatures.Procedure) -> list[str]:
    """Return the lines of an Initializer or Procedure entry, one port or binding per line."""
    lines = [f'    {name!r}: {type(value).__name__}(']
    if isinstance(value, signatures.Procedure):
        lines.append(f'        stage={value.stage!r},')
    for field in ('depends', 'produces', 'uses'):
        items = getattr(value, field)
        if not items:
            lines.append(f'        {field}={{}},')
            continue
        lines.append(f'        {field}={{')
        lines += [f'            {key!r}: {signature_code(item)},' for key, item in items.items()]
        lines.append('        },')
    lines.append('    ),')
    return lines


def generate_interfaces(interfaces: Interfaces) -> str:
    state_types, procedures, functions = interfaces
    names = ['Builtin', 'Enum', 'Function', 'Initializer', 'Int', 'List', 'Opaque', 'Option', 'Port',
             'Procedure', 'ResourceType', 'Struct', 'TypeVar']
    lines = [HEADER + '"""Native interface signatures."""', '',
             'from wirely.runtime.signatures import (', f'    {", ".join(names)},', ')', '', '',
             '# Native initializers by native name.', 'native_state_types: dict[str, Initializer] = {']
    for name, initializer in sorted(state_types.items()):
        lines += interface_lines(name, initializer)
    lines += ['}', '', '# Native procedures by native name.', 'native_procedures: dict[str, Procedure] = {']
    for name, procedure in sorted(procedures.items()):
        lines += interface_lines(name, procedure)
    lines += ['}', '', '# Runtime native functions by native name.', 'native_functions: dict[str, Function] = {']
    lines += [f'    {name!r}: {signature_code(function)},' for name, function in sorted(functions.items())]
    lines += ['}', '']
    return '\n'.join(lines)


def contracts_directories() -> tuple[Path, Path]:
    """Return the directories of the runtime and the constant function contracts."""
    return package_root / 'generated', package_root / 'compiler/generated/_contracts'


def generated_files(inputs: Iterable[Path] | None = None, *, package: str = 'wirely',
                    output_root: Path = repository_root) -> dict[Path, str]:
    """Generate an extension package from declarations without loading implementations."""
    if not all(part.isidentifier() and not keyword.iskeyword(part) for part in package.split('.')):
        raise ValueError(f'Invalid Python package {package!r}')
    source_paths = None
    if inputs is None:
        graph = compile_library()
    else:
        from wirely.compiler import parse_sources, standard_library_sources
        sources = [(str(path), path.read_text(encoding='utf-8')) for path in inputs]
        source_paths = {name for name, _ in sources}
        graph = compile_declarations(standard_library_sources() + parse_sources(sources))
    from .native_signatures import native_signatures, function_signatures as signatures_of
    interfaces = native_signatures(graph, source_paths=source_paths)
    native_locations = {value_type.native_name: package + '.generated.' + kind
                        for kind, types in [('enums', native_enums(graph)), ('structs', native_structs(graph))]
                        for value_type, declaration in types
                        if source_paths is None or declaration.source_position.filename in source_paths}
    native_locations.update({value_type.native_name: opaque_location(value_type.native_name, package)[0]
                             for value_type, declaration in native_opaque_types(graph)
                             if source_paths is None or declaration.source_position.filename in source_paths})
    exports = resource_classes(interfaces)
    exports.update({name: ('wirely.native.' + module_name(name.rpartition('.')[0]), name.rpartition('.')[2])
                    for name, declaration in native_resources(graph)
                    if source_paths is None or declaration.source_position.filename in source_paths})
    builtin_resources = resource_classes(library_interfaces(compile_library())) if inputs is not None else {}
    exports = {name: ((package + module[len('wirely'):], symbol) if name not in builtin_resources
                      else (module, symbol)) for name, (module, symbol) in exports.items()}
    directory = output_root.joinpath(*package.split('.')) / 'generated'
    constant_directory = directory.parent / 'compiler/generated'
    files = {
        directory / 'enums.py': generate_enums(graph, source_paths, source_root=output_root),
        directory / 'structs.py': generate_structs(graph, source_paths, package=package, native_locations=native_locations,
                                                     source_root=output_root),
        directory / '_signatures.py': generate_interfaces(interfaces),
    }
    for module, source in contract_sources(interfaces, resource_classes=exports, native_locations=native_locations).items():
        if module in {'__init__', 'enums', 'structs', '_bindings', '_signatures'}:
            raise ValueError(f'Native namespace produces reserved generated module {module!r}')
        files[directory / f'{module}.py'] = source
    constants = signatures_of(graph, constant=True, source_paths=source_paths)
    for module, source in constant_contract_sources(constants, native_locations=native_locations).items():
        files[constant_directory / '_contracts' / f'{module}.py'] = source
    files[constant_directory / '_contracts/__init__.py'] = HEADER
    files[directory / '_bindings.py'] = generate_bindings(
        interfaces, resource_exports={name: location for name, location in exports.items()
                                      if inputs is None or name not in builtin_resources})
    files[constant_directory / '_bindings.py'] = generate_constant_bindings(constants)
    files[directory / '__init__.py'] = HEADER + '\n'.join([
        '"""Native extension and contracts generated from Wirely declarations."""', '',
        'from wirely.runtime.extensions import (',
        '    NativeFunction, NativeInitializer, NativeProcedure, RuntimeNativeExtension,', ')',
        'from . import _bindings, _signatures',
        '', '__all__ = ["extension"]',
        'from .enums import _native_enum_types',
        'from .structs import _native_opaque_types, _native_struct_types', '',
        'extension = RuntimeNativeExtension(',
        '    states={name: NativeInitializer(signature, _bindings.states[name])',
        '            for name, signature in _signatures.native_state_types.items()},',
        '    procedures={name: NativeProcedure(signature, _bindings.procedures[name])',
        '                for name, signature in _signatures.native_procedures.items()},',
        '    functions={name: NativeFunction(signature, _bindings.functions[name])',
        '               for name, signature in _signatures.native_functions.items()},',
        '    resources=_bindings.resources, enums=_native_enum_types, structs=_native_struct_types,',
        '    opaque_types=_native_opaque_types,',
        ')', '',
    ])
    files[constant_directory / '__init__.py'] = HEADER + '\n'.join([
        '"""Constant native functions generated from Wirely declarations."""', '',
        'from wirely.compiler.extensions import CompilerNativeExtension, NativeConstantFunction',
        'from wirely.runtime.signatures import Builtin, Enum, Function, Int, List, Opaque, Option, Struct, TypeVar',
        'from . import _bindings', '', '__all__ = ["extension"]', '',
        'extension = CompilerNativeExtension(functions={',
        *(f'    {name!r}: NativeConstantFunction({signature_code(signature)}, _bindings.functions[{name!r}]),'
          for name, signature in sorted(constants.items())),
        '})', '',
    ])
    if package != 'wirely':
        # Only generated and implementation locations belong to the caller's package.
        replacements = ('wirely.compiler.generated', 'wirely.functions.',
                        'wirely.compiler.function_implementations.')
        files = {path: _replace_package(source, package, replacements) for path, source in files.items()}
        binding_path = directory / '_bindings.py'
        files[binding_path] = files[binding_path].replace('from wirely.generated.', f'from {package}.generated.')
        # State/procedure implementations belong to the selected package; resource loaders already have locations.
        files[binding_path] = files[binding_path].replace('from wirely.native.', f'from {package}.native.')
    if inputs is None:
        from wirely.compiler import parse_sources
        # Compiled without the standard library, so that top-level record names cannot clash.
        format_graph = compile_declarations(parse_sources(
            [(str(format_records_path), format_records_path.read_text(encoding='utf-8'))]))
        format_directory = package_root / 'program/generated'
        files[format_directory / 'format.py'] = generate_format_records(format_graph)
        files[format_directory / '__init__.py'] = HEADER
    return files


def _replace_package(source: str, package: str, prefixes: Iterable[str]) -> str:
    for prefix in prefixes:
        source = re.sub(r'(?m)^([ \t]*from )' + re.escape(prefix),
                        lambda match: match[1] + package + prefix[len('wirely'):], source)
    return source


def obsolete_files(files: Iterable[Path]) -> list[Path]:
    """Return generated files that no longer have declarations."""
    files = set(files)
    directories = {path.parent for path in files}
    return sorted(path for directory in directories for path in directory.glob('*.py') if path not in files)


def generate_constant_bindings(functions: Mapping[str, signatures.Function]) -> str:
    lines = [HEADER + '"""Typed loaders of constant native functions."""', '',
             'from collections.abc import Callable', '',
             'from wirely.compiler.native_functions import ConstantFunctionImplementation', '']
    entries = []
    for name in sorted(functions):
        namespace, _, function = name.rpartition('.')
        module, contract = contract_location('function', name)
        loader = '_load_' + module + '_' + snake_case(function)
        lines += ['', f'def {loader}() -> ConstantFunctionImplementation:',
                  f'    from wirely.compiler.generated._contracts.{module} import {contract}',
                  f'    from wirely.compiler.function_implementations.{module_name(namespace)} import {snake_case(function)}',
                  f'    return {contract}.implementation({snake_case(function)})', '']
        entries.append((name, loader))
    lines += ['', 'functions: dict[str, Callable[[], ConstantFunctionImplementation]] = {',
              *(f'    {name!r}: {loader},' for name, loader in entries), '}', '']
    return '\n'.join(lines)


def generate_bindings(interfaces: Interfaces, *,
                      resource_exports: Mapping[str, tuple[str, str]] | None = None) -> str:
    lines = [HEADER + '"""Typed, lazy loaders of native implementations."""', '',
             'from collections.abc import Callable', '',
             'from wirely.functions import FunctionImplementation',
             'from wirely.runtime.native_api import ProcedureImplementation, StateImplementation', '']
    kinds = (('states', 'initializer', interfaces[0], 'StateImplementation'),
             ('procedures', 'procedure', interfaces[1], 'ProcedureImplementation'),
             ('functions', 'function', interfaces[2], 'FunctionImplementation'))
    for table_name, kind, table, result in kinds:
        entries = []
        for name in sorted(table):
            prefix = name.rpartition(':')[0] if kind in ('initializer', 'procedure') else name
            namespace, _, symbol = prefix.rpartition('.')
            module, contract = contract_location(kind, name)
            loader = '_load_' + table_name + '_' + module + '_' + snake_case(contract)
            implementation = snake_case(symbol) if kind == 'function' else symbol + camel_case(name.rpartition(':')[2])
            lines += ['', f'def {loader}() -> {result}:',
                      f'    from wirely.generated.{module} import {contract}',
                      f'    from wirely.{"functions" if kind == "function" else "native"}.{module_name(namespace)} import {implementation}{" as Implementation" if kind != "function" else ""}']
            if kind == 'function':
                lines += [f'    return {contract}.implementation({implementation})', '']
            else:
                target = 'Implementation'
                lines += ['', f'    def create() -> {contract}:', f'        return {target}()', '',
                          f'    return {result}(create, {contract}._adapter)', '']
            entries.append((name, loader))
        lines += ['', f'{table_name}: dict[str, Callable[[], {result}]] = {{',
                  *(f'    {name!r}: {loader},' for name, loader in entries), '}', '']
    entries = []
    for name, (module, symbol) in (resource_classes(interfaces) if resource_exports is None else resource_exports).items():
        loader = '_load_resource_' + module_name(name)
        lines += ['', f'def {loader}() -> type:', f'    from {module} import {symbol}', f'    return {symbol}', '']
        entries.append((name, loader))
    lines += ['', 'resources: dict[str, Callable[[], type]] = {',
              *(f'    {name!r}: {loader},' for name, loader in entries), '}', '']
    return '\n'.join(lines)
